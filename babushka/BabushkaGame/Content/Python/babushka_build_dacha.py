"""Builds the playable dacha level from a tile map. Run in the editor:
Tools > Execute Python Script > this file.

Creates /Game/Babushka/Maps/Dacha with walls, the fence (gate, gap, weak part),
garden, chicken coop, bathhouse, furniture and items, grandma's patrol, lights,
the navigation volume and the player start. It also connects the Third Person
mannequins as placeholder kid and grandma. Safe to run again: it rebuilds the level.

Blockout only: grey-box shapes in flat colours. Real low-poly art replaces them later.
"""
import unreal

TILE = 100.0  # 1 tile = 1 m
MW, MH = 50, 32
LEVEL_PATH = "/Game/Babushka/Maps/Dacha"
MAT_DIR = "/Game/Babushka/Materials"

actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
levels = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
assets = unreal.get_editor_subsystem(unreal.EditorAssetSubsystem)

CUBE = unreal.load_asset("/Engine/BasicShapes/Cube")
SPHERE = unreal.load_asset("/Engine/BasicShapes/Sphere")
CYLINDER = unreal.load_asset("/Engine/BasicShapes/Cylinder")


# ---------------------------------------------------------------- tile map (same as web-sketch)
def build_map():
    m = [[","] * MW for _ in range(MH)]

    def put(x, y, c):
        if 0 <= x < MW and 0 <= y < MH:
            m[y][x] = c

    def rect(x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                put(x, y, c)

    def box(x0, y0, x1, y1, inner):
        rect(x0, y0, x1, y1, "#")
        rect(x0 + 1, y0 + 1, x1 - 1, y1 - 1, inner)

    for x in range(MW):
        put(x, 0, "="); put(x, MH - 1, "=")
    for y in range(MH):
        put(0, y, "="); put(MW - 1, y, "=")
    put(24, MH - 1, "G"); put(25, MH - 1, "G")
    for y in range(19, 23):
        put(MW - 1, y, "w")
    put(0, 26, "g")
    for row in (18, 19, 20, 23, 24, 25):
        for x in range(4, 29):
            if x not in (10, 17, 24):
                put(x, row, "~")
    box(2, 2, 32, 15, ".")
    for x in range(2, 33):
        put(x, 7, "#"); put(x, 10, "#")
    for d in (7, 17, 27):
        put(d, 7, "."); put(d, 10, ".")
    for y in list(range(3, 7)) + list(range(11, 15)):
        put(12, y, "#"); put(22, y, "#")
    put(17, 15, ".")   # entry door to the yard
    put(32, 8, ".")    # side door
    box(38, 3, 45, 8, "c"); put(41, 8, "c")
    box(38, 22, 45, 27, "h"); put(41, 22, "h")
    return m


def world(tx, ty, z=0.0):
    """Centre of a tile (or of a fractional tile position) in world space."""
    return unreal.Vector(tx * TILE + TILE / 2, ty * TILE + TILE / 2, z)


# ---------------------------------------------------------------- materials
def flat_material():
    path = MAT_DIR + "/M_BabushkaFlat"
    if assets.does_asset_exist(path):
        return unreal.load_asset(path)
    tools = unreal.AssetToolsHelpers.get_asset_tools()
    mat = tools.create_asset("M_BabushkaFlat", MAT_DIR, unreal.Material, unreal.MaterialFactoryNew())
    lib = unreal.MaterialEditingLibrary
    color = lib.create_material_expression(mat, unreal.MaterialExpressionVectorParameter, -400, 0)
    color.set_editor_property("parameter_name", "Color")
    color.set_editor_property("default_value", unreal.LinearColor(0.5, 0.5, 0.5, 1.0))
    rough = lib.create_material_expression(mat, unreal.MaterialExpressionConstant, -400, 200)
    rough.set_editor_property("r", 0.85)
    lib.connect_material_property(color, "", unreal.MaterialProperty.MP_BASE_COLOR)
    lib.connect_material_property(rough, "", unreal.MaterialProperty.MP_ROUGHNESS)
    lib.recompile_material(mat)
    assets.save_loaded_asset(mat)
    return mat


_instances = {}


def paint(name, r, g, b):
    """Material instance with a flat colour, created once."""
    if name in _instances:
        return _instances[name]
    path = "%s/MI_%s" % (MAT_DIR, name)
    if assets.does_asset_exist(path):
        mi = unreal.load_asset(path)
    else:
        tools = unreal.AssetToolsHelpers.get_asset_tools()
        mi = tools.create_asset("MI_" + name, MAT_DIR, unreal.MaterialInstanceConstant,
                                unreal.MaterialInstanceConstantFactoryNew())
        unreal.MaterialEditingLibrary.set_material_instance_parent(mi, flat_material())
    unreal.MaterialEditingLibrary.set_material_instance_vector_parameter_value(mi, "Color", unreal.LinearColor(r, g, b, 1.0))
    assets.save_loaded_asset(mi)
    _instances[name] = mi
    return mi


TEX_DIR = "/Game/Babushka/Textures"
_textured = {}


def import_textures():
    """Imports art/textures/*.png (generated by art/make_textures.py) into the project."""
    import os
    src = os.path.normpath(os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir()), "..", "art", "textures"))
    if not os.path.isdir(src):
        unreal.log_warning("No art/textures folder next to the project: using flat colours.")
        return False
    tasks = []
    for name in sorted(os.listdir(src)):
        if name.endswith(".png") and not assets.does_asset_exist(TEX_DIR + "/" + name[:-4]):
            task = unreal.AssetImportTask()
            task.filename = os.path.join(src, name)
            task.destination_path = TEX_DIR
            task.automated = True
            task.save = True
            tasks.append(task)
    if tasks:
        unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)
    return True


def world_material():
    """Master material: texture projected in world space (like box projection in Blender)."""
    path = MAT_DIR + "/M_BabushkaWorldTex"
    if assets.does_asset_exist(path):
        return unreal.load_asset(path)
    tools = unreal.AssetToolsHelpers.get_asset_tools()
    mat = tools.create_asset("M_BabushkaWorldTex", MAT_DIR, unreal.Material, unreal.MaterialFactoryNew())
    lib = unreal.MaterialEditingLibrary
    tex = lib.create_material_expression(mat, unreal.MaterialExpressionTextureObjectParameter, -700, 0)
    tex.set_editor_property("parameter_name", "Tex")
    size = lib.create_material_expression(mat, unreal.MaterialExpressionVectorParameter, -700, 200)
    size.set_editor_property("parameter_name", "TileSizeCm")
    size.set_editor_property("default_value", unreal.LinearColor(150, 150, 150, 0))
    func = lib.create_material_expression(mat, unreal.MaterialExpressionMaterialFunctionCall, -350, 0)
    func.set_editor_property("material_function", unreal.load_asset("/Engine/Functions/Engine_MaterialFunctions01/Texturing/WorldAlignedTexture"))
    lib.connect_material_expressions(tex, "", func, "TextureObject")
    lib.connect_material_expressions(size, "", func, "TextureSize")
    rough = lib.create_material_expression(mat, unreal.MaterialExpressionScalarParameter, -350, 250)
    rough.set_editor_property("parameter_name", "Roughness")
    rough.set_editor_property("default_value", 0.8)
    lib.connect_material_property(func, "XYZ Texture", unreal.MaterialProperty.MP_BASE_COLOR)
    lib.connect_material_property(rough, "", unreal.MaterialProperty.MP_ROUGHNESS)
    lib.recompile_material(mat)
    assets.save_loaded_asset(mat)
    return mat


def textured(name, texture, tile_cm, fallback, rough=0.8):
    """Material instance with a world-aligned texture; flat colour if anything is missing."""
    if name in _textured:
        return _textured[name]
    result = paint(name + "Flat", *fallback)
    try:
        tex = unreal.load_asset(TEX_DIR + "/" + texture)
        if tex:
            path = "%s/MI_%s" % (MAT_DIR, name)
            if assets.does_asset_exist(path):
                mi = unreal.load_asset(path)
            else:
                tools = unreal.AssetToolsHelpers.get_asset_tools()
                mi = tools.create_asset("MI_" + name, MAT_DIR, unreal.MaterialInstanceConstant, unreal.MaterialInstanceConstantFactoryNew())
                unreal.MaterialEditingLibrary.set_material_instance_parent(mi, world_material())
            lib = unreal.MaterialEditingLibrary
            lib.set_material_instance_texture_parameter_value(mi, "Tex", tex)
            lib.set_material_instance_vector_parameter_value(mi, "TileSizeCm", unreal.LinearColor(tile_cm, tile_cm, tile_cm, 0))
            lib.set_material_instance_scalar_parameter_value(mi, "Roughness", rough)
            assets.save_loaded_asset(mi)
            result = mi
    except Exception as error:
        unreal.log_warning("Texture %s not applied (%s), flat colour used." % (texture, error))
    _textured[name] = result
    return result


# ---------------------------------------------------------------- spawning helpers
def block(mesh, center, size_cm, material, label, collide=True, rot=None):
    """Static mesh scaled to an exact size in cm (basic shapes are 100 cm)."""
    actor = actors.spawn_actor_from_class(unreal.StaticMeshActor, center, rot or unreal.Rotator(0, 0, 0))
    comp = actor.static_mesh_component
    comp.set_static_mesh(mesh)
    comp.set_material(0, material)
    if not collide:
        comp.set_collision_profile_name("NoCollision")
    actor.set_actor_scale3d(unreal.Vector(size_cm[0] / 100.0, size_cm[1] / 100.0, size_cm[2] / 100.0))
    actor.set_actor_label(label)
    actor.set_folder_path("Dacha/" + label.split("_")[0])
    return actor


def runs(m, chars):
    """Merge tiles into long boxes: horizontal runs first, then vertical, then single tiles."""
    used = [[False] * MW for _ in range(MH)]
    out = []
    for y in range(MH):
        x = 0
        while x < MW:
            if m[y][x] in chars:
                x0 = x
                while x < MW and m[y][x] in chars:
                    x += 1
                if x - x0 >= 2:
                    out.append((x0, y, x - x0, 1))
                    for i in range(x0, x):
                        used[y][i] = True
            else:
                x += 1
    for x in range(MW):
        y = 0
        while y < MH:
            if m[y][x] in chars and not used[y][x]:
                y0 = y
                while y < MH and m[y][x] in chars and not used[y][x]:
                    y += 1
                out.append((x, y0, 1, y - y0))
                for i in range(y0, y):
                    used[i][x] = True
            else:
                y += 1
    return out


def tile_box(x, y, w, h, height, z0, material, label, collide=True):
    center = unreal.Vector((x + w / 2.0) * TILE, (y + h / 2.0) * TILE, z0 + height / 2.0)
    return block(CUBE, center, (w * TILE, h * TILE, height), material, label, collide)


def spawn(cls, tx, ty, z=0.0, yaw=0.0, label=None):
    actor = actors.spawn_actor_from_class(cls, world(tx, ty, z), unreal.Rotator(0, 0, yaw))
    if label:
        actor.set_actor_label(label)
    return actor


def interactable(kind, tx, ty, mesh, size, color, label, z=None, yaw=0.0, **props):
    height = size[2]
    actor = spawn(unreal.BabushkaInteractable, tx, ty, height / 2.0 if z is None else z, yaw, label)
    actor.set_editor_property("kind", kind)
    for key, value in props.items():
        actor.set_editor_property(key, value)
    comp = actor.get_editor_property("mesh")
    comp.set_static_mesh(mesh)
    comp.set_material(0, color)
    actor.set_actor_scale3d(unreal.Vector(size[0] / 100.0, size[1] / 100.0, size[2] / 100.0))
    actor.set_folder_path("Dacha/Items")
    return actor


def zone(kind, x0, y0, x1, y1, label):
    """Trigger box over tiles x0..x1, y0..y1 (inclusive)."""
    cx, cy = (x0 + x1 + 1) / 2.0 * TILE, (y0 + y1 + 1) / 2.0 * TILE
    actor = actors.spawn_actor_from_class(unreal.BabushkaZone, unreal.Vector(cx, cy, 150), unreal.Rotator(0, 0, 0))
    actor.set_editor_property("kind", kind)
    actor.get_editor_property("box").set_box_extent(
        unreal.Vector((x1 - x0 + 1) * TILE / 2.0, (y1 - y0 + 1) * TILE / 2.0, 200))
    actor.set_actor_label(label)
    actor.set_folder_path("Dacha/Zones")
    return actor


def point_light(tx, ty, intensity, color, radius, label, shadows=False):
    actor = actors.spawn_actor_from_class(unreal.PointLight, world(tx, ty, 230), unreal.Rotator(0, 0, 0))
    comp = actor.point_light_component
    comp.set_mobility(unreal.ComponentMobility.MOVABLE)
    comp.set_editor_property("intensity_units", unreal.LightUnits.CANDELAS)
    comp.set_editor_property("intensity", intensity)
    comp.set_editor_property("light_color", color)
    comp.set_editor_property("attenuation_radius", radius)
    comp.set_editor_property("cast_shadows", shadows)
    actor.set_actor_label(label)
    actor.set_folder_path("Dacha/Lights")


# ---------------------------------------------------------------- characters
def connect_characters():
    registry = unreal.AssetRegistryHelpers.get_asset_registry()
    found = registry.get_assets_by_path("/Game/Characters", recursive=True)

    def first(cls, words):
        items = [d for d in found if str(d.asset_class_path.asset_name) == cls]
        for word in words:
            for d in items:
                if word.lower() in str(d.asset_name).lower():
                    return d
        return items[0] if items else None

    kid = first("SkeletalMesh", ["SKM_Manny", "Manny"])
    grandma = first("SkeletalMesh", ["SKM_Quinn", "Quinn", "Manny"])
    anim = first("AnimBlueprint", ["ABP_Manny", "ABP_Unarmed", "Manny", "Unarmed", "ABP_"])
    if not (kid and grandma and anim):
        unreal.log_warning("Third Person pack not found: kid and grandma will be invisible capsules. "
                           "Add it (docs/SETUP.md) and run this script again.")
        return
    anim_class = unreal.load_object(None, "%s.%s_C" % (anim.package_name, anim.asset_name))
    settings = unreal.get_default_object(unreal.BabushkaSettings)
    settings.set_character_assets(unreal.load_asset(str(kid.package_name)),
                                  unreal.load_asset(str(grandma.package_name)), anim_class)
    unreal.log("Characters: kid %s, grandma %s, animation %s" % (kid.asset_name, grandma.asset_name, anim.asset_name))


# ---------------------------------------------------------------- level
def open_fresh_level():
    if assets.does_asset_exist(LEVEL_PATH):
        levels.load_level(LEVEL_PATH)
        # Remove only what this script built (everything lives in the "Dacha" folder).
        old = [a for a in actors.get_all_level_actors() if str(a.get_folder_path()).startswith("Dacha")]
        if old:
            actors.destroy_actors(old)
    else:
        levels.new_level(LEVEL_PATH)


def env(actor, label):
    actor.set_actor_label(label)
    actor.set_folder_path("Dacha/Env")
    return actor


def build():
    connect_characters()
    open_fresh_level()
    m = build_map()

    import_textures()
    # Textures from art/textures (same look as art/renders), flat colours as a fallback.
    wood = textured("FloorPaint", "T_FloorPaint", 200, (0.32, 0.16, 0.1), rough=0.55)
    wall = textured("Wallpaper", "T_Wallpaper", 120, (0.75, 0.8, 0.65))
    siding = textured("Siding", "T_Siding", 160, (0.5, 0.65, 0.62))
    grass = textured("Grass", "T_Grass", 300, (0.07, 0.16, 0.08), rough=0.95)
    soil = textured("Soil", "T_Soil", 150, (0.16, 0.1, 0.06), rough=1.0)
    fence = textured("Fence", "T_Fence", 140, (0.3, 0.22, 0.13))
    logs = textured("Logs", "T_Logs", 140, (0.4, 0.27, 0.15))
    coop = textured("Boards", "T_Boards", 120, (0.3, 0.25, 0.15))
    banya = textured("BanyaFloor", "T_Boards", 120, (0.25, 0.28, 0.3))
    road = paint("Road", 0.12, 0.12, 0.13)

    # Ground with room outside the fence for the exits; the house floor sits 1 cm higher.
    tile_box(-8, -8, MW + 16, MH + 16, 20, -20, road, "Ground_Road")
    tile_box(0, 0, MW, MH, 20, -19, grass, "Ground_Yard")
    tile_box(3, 3, 29, 12, 20, -18, wood, "Floor_House")
    tile_box(39, 4, 6, 4, 20, -18, coop, "Floor_Coop")
    tile_box(39, 23, 6, 4, 20, -18, banya, "Floor_Banya")

    for i, (x, y, w, h) in enumerate(runs(m, "#")):
        # House perimeter gets painted siding, rooms get wallpaper, the bathhouse logs, the coop boards.
        on_house_edge = (x in (2, 32) and w == 1) or (y in (2, 15) and h == 1)
        if x >= 38 and y >= 20:
            material = logs
        elif x >= 38:
            material = fence
        else:
            material = siding if on_house_edge else wall
        tile_box(x, y, w, h, 260, 0, material, "Wall_%02d" % i)
    for i, (x, y, w, h) in enumerate(runs(m, "=")):
        tile_box(x, y, w, h, 130, 0, fence, "Fence_%02d" % i)
    for i, (x, y, w, h) in enumerate(runs(m, "~")):
        tile_box(x, y, w, h, 12, 0, soil, "Garden_%02d" % i, collide=False)

    # Weak fence on the east side (ball breaks it), the gap on the west side (thin kids only).
    weak = spawn(unreal.BabushkaBreakableFence, MW - 1, 20.5, 65, 0, "Fence_Weak")
    planks = weak.get_editor_property("planks")
    planks.set_static_mesh(CUBE)
    planks.set_material(0, paint("FenceWeak", 0.4, 0.3, 0.17))
    weak.set_actor_scale3d(unreal.Vector(0.3, 4.0, 1.3))
    gap = spawn(unreal.BabushkaFenceGap, 0, 26, 65, 0, "Fence_Gap")
    blocker = gap.get_editor_property("blocker")
    blocker.set_static_mesh(CUBE)
    blocker.set_material(0, paint("FenceGap", 0.35, 0.26, 0.15))
    gap.set_actor_scale3d(unreal.Vector(0.3, 1.0, 0.6))  # low fence board: the gap is underneath

    K = unreal.BabushkaInteractKind
    furniture = paint("Furniture", 0.45, 0.3, 0.18)
    cloth = textured("Carpet", "T_Carpet", 160, (0.55, 0.12, 0.12), rough=0.95)
    bush = paint("Bush", 0.12, 0.3, 0.12)
    glass = paint("Glass", 0.6, 0.75, 0.7)
    item = paint("Item", 0.9, 0.62, 0.2)

    # Hiding spots (GDD 4).
    interactable(K.HIDE, 4, 4, CUBE, (190, 100, 50), cloth, "Hide_KidsBed")
    interactable(K.HIDE, 14, 13.5, CUBE, (100, 60, 210), furniture, "Hide_Wardrobe", b_needs_thin_kid=True)
    interactable(K.HIDE, 8, 10.6, CUBE, (160, 10, 130), cloth, "Hide_Carpet", z=150)
    interactable(K.HIDE, 30, 13.5, CYLINDER, (80, 80, 90), glass, "Hide_Jars")
    interactable(K.HIDE, 36, 17, SPHERE, (160, 160, 120), bush, "Hide_Currants")
    interactable(K.HIDE, 7, 28, SPHERE, (160, 160, 120), bush, "Hide_Raspberries")
    # Items and actions.
    interactable(K.PHONE, 14, 3.2, CUBE, (140, 50, 160), glass, "Item_Sideboard_Phone")
    interactable(K.MONEY, 30, 3.3, CYLINDER, (40, 40, 50), glass, "Item_Jar_Money", z=95)
    interactable(K.SHOES, 19, 13.5, CUBE, (50, 30, 15), item, "Item_Shoes")
    interactable(K.KEY, 43, 5, CUBE, (20, 10, 5), item, "Item_Key", z=110)
    interactable(K.PIE, 27, 5, CUBE, (140, 90, 75), furniture, "Item_Table_Pies", pies_left=3)
    interactable(K.TV, 3.4, 13, CUBE, (40, 90, 70), paint("TV", 0.05, 0.05, 0.06), "Item_TV", z=90, yaw=0.0)
    interactable(K.GATE, 24.5, MH - 1, CUBE, (200, 25, 140), fence, "Item_Gate")
    # Grandma's bed and the coop perches as plain scenery.
    block(CUBE, world(19, 4, 25), (190, 100, 50), cloth, "Prop_GrandmaBed")
    block(CUBE, world(5, 12, 45), (60, 60, 90), furniture, "Prop_Armchair")

    # Zones.
    Z = unreal.BabushkaZoneKind
    zone(Z.HOUSE, 3, 3, 31, 14, "Zone_House")
    zone(Z.GARDEN, 4, 18, 28, 20, "Zone_GardenNorth")
    zone(Z.GARDEN, 4, 23, 28, 25, "Zone_GardenSouth")
    zone(Z.CHICKEN_COOP, 39, 4, 44, 8, "Zone_Coop")
    zone(Z.BANYA, 39, 23, 44, 26, "Zone_Banya")
    zone(Z.EXIT, -6, MH + 1, MW + 5, MH + 4, "Zone_ExitSouth")
    zone(Z.EXIT, -6, -6, -2, MH + 4, "Zone_ExitWest")
    zone(Z.EXIT, MW + 1, -6, MW + 5, MH + 4, "Zone_ExitEast")

    # Grandma, her patrol and her bed (she naps from 01:00 to 02:30).
    for i, (x, y) in enumerate([(16, 5), (26, 4), (17, 8), (7, 12), (17, 12), (27, 12), (7, 8), (17, 17)]):
        wp = spawn(unreal.BabushkaWaypoint, x, y, 90, 0, "Waypoint_%02d" % i)
        wp.set_folder_path("Dacha/Grandma")
    bed = spawn(unreal.BabushkaWaypoint, 19, 5.2, 90, 0, "Waypoint_Bed")
    bed.set_editor_property("b_is_bed", True)
    bed.set_folder_path("Dacha/Grandma")
    granny = spawn(unreal.BabushkaGrandma, 17, 12, 100, 0, "Grandma")
    granny.set_folder_path("Dacha/Grandma")

    env(spawn(unreal.PlayerStart, 7, 5, 100, 0), "PlayerStart_KidsRoom")

    # Night light: cold moon, a soft blue fill instead of a sky light, warm lamps in the rooms.
    moon = actors.spawn_actor_from_class(unreal.DirectionalLight, unreal.Vector(0, 0, 1000), unreal.Rotator(0, -50, 35))
    moon.light_component.set_editor_property("intensity", 1.5)
    moon.light_component.set_editor_property("light_color", unreal.Color(150, 170, 255, 255))
    moon.light_component.set_mobility(unreal.ComponentMobility.MOVABLE)
    env(moon, "Light_Moon")
    fill = actors.spawn_actor_from_class(unreal.DirectionalLight, unreal.Vector(0, 0, 1000), unreal.Rotator(0, -90, 0))
    fill.light_component.set_editor_property("intensity", 0.6)
    fill.light_component.set_editor_property("light_color", unreal.Color(90, 110, 170, 255))
    fill.light_component.set_editor_property("cast_shadows", False)
    fill.light_component.set_mobility(unreal.ComponentMobility.MOVABLE)
    env(fill, "Light_Fill")
    warm = unreal.Color(255, 190, 120, 255)
    for i, (x, y) in enumerate([(7, 5), (17, 5), (27, 5), (7, 12), (17, 12), (27, 12), (17, 8.5)]):
        point_light(x, y, 18.0, warm, 650.0, "Light_Room_%d" % i)
    point_light(17, 16.5, 10.0, warm, 500.0, "Light_Porch", shadows=True)

    pp = actors.spawn_actor_from_class(unreal.PostProcessVolume, unreal.Vector(0, 0, 0), unreal.Rotator(0, 0, 0))
    pp.set_editor_property("unbound", True)
    env(pp, "PostProcess_Night")
    try:
        s = pp.settings
        s.set_editor_property("override_auto_exposure_method", True)
        s.set_editor_property("auto_exposure_method", unreal.AutoExposureMethod.AEM_MANUAL)
        s.set_editor_property("override_auto_exposure_apply_physical_camera_exposure", True)
        s.set_editor_property("auto_exposure_apply_physical_camera_exposure", False)
        s.set_editor_property("override_auto_exposure_bias", True)
        s.set_editor_property("auto_exposure_bias", 2.0)
        s.set_editor_property("override_vignette_intensity", True)
        s.set_editor_property("vignette_intensity", 0.5)
        pp.set_editor_property("settings", s)
    except Exception as error:  # property names differ between engine versions
        unreal.log_warning("Exposure not set (%s). Adjust PostProcess_Night > Exposure by hand if the scene is too dark." % error)

    fog = actors.spawn_actor_from_class(unreal.ExponentialHeightFog, unreal.Vector(0, 0, 0), unreal.Rotator(0, 0, 0))
    env(fog, "Fog_Night")

    # Navigation for grandma over the whole yard.
    # Grandma also builds the nav mesh around herself at runtime (navigation invoker), so this is a backup.
    nav = actors.spawn_actor_from_class(unreal.NavMeshBoundsVolume, unreal.Vector(MW * TILE / 2, MH * TILE / 2, 100), unreal.Rotator(0, 0, 0))
    unreal.BabushkaEditorHelpers.make_box_brush(nav, unreal.Vector(MW * TILE + 400, MH * TILE + 400, 600))
    env(nav, "NavMeshBounds")

    levels.save_current_level()
    unreal.log("Dacha built: %s. Press Play." % LEVEL_PATH)


