"""Writes the advance widths of the game's font into C# so the layout model can measure text without Unity.

    python3 farm/tools/font_metrics.py

Reads Assets/SunnyValley/Resources/Fonts/Nunito-ExtraBold.ttf (needs fontTools) and writes
Assets/SunnyValley/Game/Layout/FontMetrics.Nunito.cs. Run it again if the font changes.
"""
import os

from fontTools.ttLib import TTFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "unity", "SunnyValley", "Assets", "SunnyValley")
FONT = os.path.join(ROOT, "Resources", "Fonts", "Nunito-ExtraBold.ttf")
OUT = os.path.join(ROOT, "Game", "Layout", "FontMetrics.Nunito.cs")


def main():
    font = TTFont(FONT)
    upm = font["head"].unitsPerEm
    hhea, os2 = font["hhea"], font["OS/2"]
    # Unity's legacy Text takes the line height from the font; the larger of the two sets of metrics is the safe bet
    line = max(hhea.ascent - hhea.descent + hhea.lineGap, os2.usWinAscent + os2.usWinDescent)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    pairs = sorted((cp, hmtx[g][0]) for cp, g in cmap.items() if cp < 0x10000)
    rows_codes, rows_adv = [], []
    for i in range(0, len(pairs), 20):
        chunk = pairs[i:i + 20]
        rows_codes.append("            " + ", ".join(str(cp) for cp, _ in chunk) + ",")
        rows_adv.append("            " + ", ".join(str(a) for _, a in chunk) + ",")
    codes = "\n".join(rows_codes)
    advances = "\n".join(rows_adv)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""// Generated by farm/tools/font_metrics.py from Nunito-ExtraBold.ttf. Do not edit by hand.
namespace SunnyValley.Layout
{{
    public static partial class FontMetrics
    {{
        /// <summary>Font units per em of Nunito ExtraBold.</summary>
        public const int UnitsPerEm = {upm};

        /// <summary>Height of one line in font units (ascent + descent + gap, the larger of hhea and OS/2).</summary>
        public const int LineUnits = {line};

        /// <summary>Code points the font has, ascending.</summary>
        static readonly int[] Codes =
        {{
{codes}
        }};

        /// <summary>Advance width of each code point in font units.</summary>
        static readonly int[] Advances =
        {{
{advances}
        }};
    }}
}}
""")
    print(f"{len(pairs)} glyphs, line {line}/{upm} -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
